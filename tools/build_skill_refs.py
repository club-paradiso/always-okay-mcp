#!/usr/bin/env python3
"""Build the Skill's data-derived references from the server's data snapshot.

  python3 tools/build_skill_refs.py          # writes principles.md, evidence-map.md, tensions.md
  python3 tools/build_skill_refs.py --check  # exits 1 if any of them is out of date or a reference dangles

Sources: src/always_okay_mcp/data/{framework,claims,notes,sources,tensions}.json.
Every claim or tension ID a principle cites must resolve; the build fails otherwise.
tensions.md carries only the method-relevant part of each tension (how to apply the principle and the
status), never the source-by-source narrative, so no dispute account enters the Skill.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "src/always_okay_mcp/data"
REFS = ROOT / "plugins/always-okay/skills/always-okay/references"
GEN = "<!-- Generated by tools/build_skill_refs.py from src/always_okay_mcp/data. Do not edit by hand. -->\n"
MAX_SOURCES = 6


def load(name):
    return json.loads((DATA / f"{name}.json").read_text(encoding="utf-8"))


FW = load("framework")
CLAIMS = {c["claim_id"]: c for c in load("claims")}
NOTES = {n["note_id"]: n for n in load("notes")}
SOURCES = {s["source_id"]: s for s in load("sources")}
TENSIONS = {t["id"]: t for t in load("tensions")}
STAGES = {s["id"]: s for s in FW["stages"]}


def cited_claims(p):
    ids = list(p["claims"])
    for m in re.findall(r"CL-\d{3}", p["limits"] + p["rule"]):
        if "MHJ-" + m not in ids:
            ids.append("MHJ-" + m)
    return ids


def cited_tensions(p):
    ids = list(p["tensions"])
    for m in re.findall(r"CX-\d{2}", p["limits"] + p["rule"]):
        if "MHJ-" + m not in ids:
            ids.append("MHJ-" + m)
    return ids


def dangling():
    bad = []
    for p in FW["principles"]:
        bad += [(p["id"], c) for c in cited_claims(p) if c not in CLAIMS]
        bad += [(p["id"], t) for t in cited_tensions(p) if t not in TENSIONS]
        for c in cited_claims(p):
            for e in CLAIMS.get(c, {}).get("evidence", []):
                if e not in NOTES or NOTES[e]["source_id"] not in SOURCES:
                    bad.append((c, e))
    return bad


def evidence_line(p):
    s = p["support"]
    claims = ", ".join(p["claims"])
    return (f"- Evidence: {s['class'].lower()}, {s['confidence']} confidence, {s['units']} independent sources "
            f"({s['nondispute_units']} outside the dispute period); claims {claims}")


def principles_md():
    out = [GEN, "# Principles\n\n",
           f"{len(FW['principles'])} principles in eight stages (P15 merged into P05 in v1.1). Support figures are "
           "computed from the research claim database; `confidence` is about the evidence, not about the "
           "principle's fit to your case. Application conditions (MHJ-CX-##) are in `tensions.md`.\n\n",
           "## Contents\n\n"]
    out += [f"- Stage {sid} — {st['name']}\n" for sid, st in STAGES.items()]
    for sid, st in STAGES.items():
        out.append(f"\n## Stage {sid} — {st['name']}\n\n*{st['question']}*\n")
        for p in [x for x in FW["principles"] if x["stage"] == sid]:
            tag = "" if p["status"] == "core" else " *(supporting — stated stance, weaker evidence)*"
            out.append(f"\n### {p['id']} {p['title']}{tag}\n\n{p['rule']}\n\n")
            out.append(f"- Limits: {p['limits']}\n")
            out.append(f"- Guards against: {p['guards_against']}\n")
            ts = cited_tensions(p)
            if ts:
                out.append(f"- Application conditions: {', '.join(ts)} (see `tensions.md`) — "
                           "the rule is a default, not an absolute\n")
            out.append(evidence_line(p) + "\n")
    return "".join(out)


def src_label(note):
    s = SOURCES[note["source_id"]]
    pub = s["publication"]
    pub = pub if len(pub) <= 40 else pub[:40]
    lab = f"{pub}, {s['date'][:7]}" if s.get("date") else pub
    return lab + (", dispute context" if note["dispute_context"] else "")


def evidence_map_md():
    out = [GEN, "# Evidence map\n\n",
           "Use this when the user asks *why* a principle holds or where it comes from. Paraphrased; sources are "
           "public interviews, talks, credits and collaborator accounts. Each principle lists the claims it rests "
           "on, including claims named in its limits. Full chain through the MCP server (`trace`).\n\n",
           "## Contents\n\n"]
    out += [f"- {p['id']} {p['title']}\n" for p in FW["principles"]]
    for p in FW["principles"]:
        out.append(f"\n## {p['id']} {p['title']}\n\n")
        for cid in cited_claims(p):
            c = CLAIMS[cid]
            labels = []
            for e in c["evidence"]:
                lab = src_label(NOTES[e])
                if lab not in labels:
                    labels.append(lab)
            more = " …" if len(labels) > MAX_SOURCES else ""
            out.append(f"- **{cid}** ({c['epistemic_class'].lower()}, {c['confidence']}): {c['claim']}\n")
            out.append(f"  - Sources: {'; '.join(labels[:MAX_SOURCES])}{more}\n")
    return "".join(out)


def _field(body, name):
    m = re.search(r"\*\*" + re.escape(name) + r"\*\*(.*?)(?=\n- \*\*|\Z)", body, re.S)
    return " ".join(m.group(1).split()).strip(" :") if m else ""


def _status(body):
    st = _field(body, "Status:")
    return re.sub(r"\s*\([^)]*(litigation|dispute|lawsuit|court)[^)]*\)", "", st, flags=re.I).strip()


def tensions_md():
    users = {}
    for p in FW["principles"]:
        for t in cited_tensions(p):
            users.setdefault(t, []).append(p["id"])
    out = [GEN, "# Application conditions\n\n",
           "Where a principle was applied differently depending on the situation, or where sources word a credit "
           "differently, the research records it here. Read these as conditions for applying the principle well, "
           "not as criticism of anyone. Each entry gives only what changes how the lens is used; the source-by-"
           "source record stays in the research data. Never use these entries for commentary on any person or "
           "dispute.\n\n"]
    for tid in sorted(users):
        t = TENSIONS[tid]
        out.append(f"## {tid} {t['title']}\n\n")
        out.append(f"- Principles: {', '.join(users[tid])}\n")
        how = _field(t["body"], "Affects the creative model?")
        minor = bool(re.match(r"minor\b", how, re.I))
        how = re.sub(r"^(yes|minor|no)\b[.:;,]?\s*", "", how, flags=re.I)
        how = how[:1].upper() + how[1:] if how else "No change to how the principle is applied; context only."
        out.append(f"- How to apply{' (minor)' if minor else ''}: {how}\n")
        st = _status(t["body"])
        if st:
            out.append(f"- Status: {st}\n")
        out.append("\n")
    return "".join(out)


TARGETS = {"principles.md": principles_md, "evidence-map.md": evidence_map_md, "tensions.md": tensions_md}


def main(argv):
    bad = dangling()
    if bad:
        print("dangling references:", bad)
        return 1
    stale = []
    for name, fn in TARGETS.items():
        text = fn()
        path = REFS / name
        if "--check" in argv:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        print("out of date:", ", ".join(stale), "— run python3 tools/build_skill_refs.py")
        return 1
    print("ok" if "--check" in argv else "wrote " + ", ".join(TARGETS))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
